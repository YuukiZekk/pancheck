# 画质档位（内核的 U/H/S/? 与带 * 的体积推断档）
TIERS = {'U': '4K', 'H': '1080p', 'S': '720p 及以下', '?': '未知'}


def tier(t):
    t = str(t or '?')
    name = TIERS.get(t.rstrip('*'), t)
    return name + '（按体积推断）' if t.endswith('*') else name


def bucket(b):
    return BUCKETS.get(b, (b, '', ''))[0]


def stage(s):
    return STAGES.get(s, (s, ''))[0]


def cls(s, c):
    return CLASSES.get('%s|%s' % (s, c), c)


_T = r'([UHS?]\*?)'
_BASIS = [
    (re.compile(r'原盘有正经份\(([\d.]+)GB/' + _T + r'\)'),
     lambda m: '原盘区有像样的一份（%sGB，%s）' % (m.group(1), tier(m.group(2)))),
    (re.compile(r'原盘份也不大\(([\d.]+)GB/' + _T + r'\)'),
     lambda m: '原盘区那份也不大（%sGB，%s），需要对比着看' % (m.group(1), tier(m.group(2)))),
    (re.compile(r'区内有更好份但同属小文件层,合并看'), lambda m: '合集里有更好的一份，但也是小文件，需要对比着看'),
    (re.compile(r'Emby库内有(\d+)p\(纵向\)'), lambda m: 'Emby 片库里已有 %sp 版本' % m.group(1)),
    (re.compile(r'手里' + _T + r'档 vs 库内(\d+)p'), lambda m: '这份是 %s，库里只有 %sp' % (tier(m.group(1)), m.group(2))),
    (re.compile(r'片名命中,库内(\d+)p'), lambda m: '片名对上了库里的 %sp 版本（没有 TMDB 编号，仅供参考）' % m.group(1)),
    (re.compile(r'^库内(\d+)p$'), lambda m: '库里已有 %sp 版本' % m.group(1)),
    (re.compile(r'^库内无此片$'), lambda m: 'Emby 片库里没有这部片'),
]


def plain_basis(s):
    """把内核给的判定依据翻成白话（只改显示文字，不影响判定）。"""
    for pat, fn in _BASIS:
        s = pat.sub(fn, s)
    return s


def as_json():
    return {'buckets': {k: {'name': v[0], 'desc': v[1], 'action': v[2]} for k, v in BUCKETS.items()},
            'stages': {k: {'name': v[0], 'desc': v[1]} for k, v in STAGES.items()},
            'classes': CLASSES, 'short': SHORT}
